def _required(name: str) -> str:
    value = os.getenv(name, "").strip()
    if not value:
        raise RuntimeError(f"{name} is required. Copy .env.example to .env and fill it in.")
    return value


def _owner_ids(value: str) -> frozenset[int]:
    try:
        ids = frozenset(int(item.strip()) for item in value.split(",") if item.strip())
    except ValueError as exc:
        raise RuntimeError("OWNER_IDS must be a comma-separated list of numeric Telegram IDs.") from exc
    if not ids:
        raise RuntimeError("OWNER_IDS must contain at least one numeric Telegram ID.")
    return ids


def load_settings() -> Settings:
    """Load and lightly validate runtime settings without logging any secret."""
    key = _required("ENCRYPTION_KEY")
    try:
        decoded = base64.urlsafe_b64decode(key.encode())
    except Exception as exc:  # Fernet gives a clearer validation later; this catches obvious mistakes.
        raise RuntimeError("ENCRYPTION_KEY must be a Fernet key generated by cryptography.") from exc
    if len(decoded) != 32:
        raise RuntimeError("ENCRYPTION_KEY must be a valid Fernet key (32 decoded bytes).")

    log_chat_raw = os.getenv("LOG_CHAT_ID", "").strip()
    return Settings(
        api_id=int(_required("API_ID")),
        api_hash=_required("API_HASH"),
        bot_token=_required("BOT_TOKEN"),
        mongo_uri=_required("MONGO_URI"),
        encryption_key=key,
        owner_ids=_owner_ids(_required("OWNER_IDS")),
        main_channel=os.getenv("MAIN_CHANNEL", "@ZCYT_29266").strip(),
        support_channel=os.getenv("SUPPORT_CHANNEL", "@ZCYT_2026").strip(),
        updates_channel=os.getenv("UPDATES_CHANNEL", "@ZCYT_2026").strip(),
        tutorial_channel=os.getenv("TUTORIAL_CHANNEL", "@ZCYT_2026").strip(),
        admin_username=os.getenv("ADMIN_USERNAME", "@ZCQXx").strip(),
        log_chat_id=int(log_chat_raw) if log_chat_raw else None,
        workdir=Path(os.getenv("WORKDIR", "./data")).resolve(),
    )


def plan_at_least(plan: str, minimum: str) -> bool:
    return PLAN_ORDER.get(plan, 0) >= PLAN_ORDER[minimum]
