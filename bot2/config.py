@dataclass(frozen=True, slots=True)
class Settings:
    api_id: int
    api_hash: str
    bot_token: str
    mongo_uri: str
    encryption_key: str
    owner_ids: frozenset[int]
    main_channel: str
    support_channel: str
    updates_channel: str
    tutorial_channel: str
    admin_username: str
    log_chat_id: int | None
    workdir: Path

    @property
    def admin_url(self) -> str:
        return f"https://t.me/{self.admin_username.lstrip('@')}"

